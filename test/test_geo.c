static int AngleDiff(int a, int b)
{
    int d = abs(a - b) % 360;
    return d > 180 ? 360 - d : d;
}

int main(void)
{
    for (size_t i = 0; i < sizeof VECS / sizeof VECS[0]; i++) {
        const Vec *v = &VECS[i];
        uint16_t b;
        const uint32_t d = GEO_Distance(v->lat1, v->lon1, v->lat2, v->lon2, &b);
        // flat-earth: within 0.5% (1.5% beyond 100 km), + 25 m for the 18 m position steps
        const double err = (double)d - v->metres, tol = v->metres * (v->metres > 100000 ? 0.015 : 0.005) + 25;
        CHECK(err < tol && -err < tol, "vec %zu: %u m, expected %u", i, d, v->metres);
        // bearing: within 1 degree; looser when the positions are only a few steps
        // apart, and beyond 100 km (rhumb line vs the great circle's initial bearing)
        const int btol = v->metres < 1000 ? 6 : v->metres > 100000 ? 4 : 1;
        CHECK(AngleDiff(b, v->bearing) <= btol, "vec %zu: bearing %u, expected %u", i, b, v->bearing);
    }

    uint16_t b = 999;
    CHECK(GEO_Distance(100, 200, 100, 200, &b) == 0 && b == 0, "same place: bearing %u", b);
    CHECK(GEO_Distance(0, 0, 6000, 0, &b) > 110000 && b == 0, "north");
    GEO_Distance(0, 0, 0, 6000, &b);   CHECK(b == 90, "east: %u", b);
    GEO_Distance(0, 0, -6000, 0, &b);  CHECK(b == 180, "south: %u", b);
    GEO_Distance(0, 0, 0, -6000, &b);  CHECK(b == 270, "west: %u", b);
    CHECK(GEO_Distance(0, 0, 6000, 0, NULL) > 0, "no bearing wanted");

    static const struct { uint32_t m; const char *s; } FMT[] = {
        { 0, "0m" }, { 850, "850m" }, { 999, "999m" }, { 1000, "1.0km" }, { 1049, "1.0km" },
        { 1050, "1.1km" }, { 9949, "9.9km" }, { 9950, "10km" }, { 123456, "123km" },
        { 1234567, "1235km" }, { 20000000, "9999km" },
    };
    for (size_t i = 0; i < sizeof FMT / sizeof FMT[0]; i++) {
        char s[12];
        GEO_FormatDistance(FMT[i].m, s);
        CHECK(!strcmp(s, FMT[i].s), "%u m -> %s, expected %s", FMT[i].m, s, FMT[i].s);
    }

    static const struct { uint16_t b; const char *s; } CMP[] = {
        { 0, "N" }, { 22, "N" }, { 23, "NE" }, { 45, "NE" }, { 90, "E" }, { 135, "SE" },
        { 180, "S" }, { 225, "SW" }, { 270, "W" }, { 315, "NW" }, { 337, "NW" }, { 338, "N" }, { 359, "N" },
    };
    for (size_t i = 0; i < sizeof CMP / sizeof CMP[0]; i++)
        CHECK(!strcmp(GEO_Compass(CMP[i].b), CMP[i].s), "%u -> %s", CMP[i].b, GEO_Compass(CMP[i].b));

    printf("%d passed, %d failed\n", sPass, sFail);
    return sFail != 0;
}
